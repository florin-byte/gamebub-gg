#!/usr/bin/env python3
"""Generate tb_sms.sv: a simulation testbench around the SMS_MiSTer `system` and `video` entities.

The port list of `system` is read from its GHDL-generated Verilog, so every port is connected: inputs
that the test does not drive are tied to 0, outputs that it does not use are left open. The ROM is
replayed through ROMAD/ROMDT/ROMEN like the MiSTer download stream, then read with the same mask as
SMS.sv; the clock enables are the ones of SMS.sv.

Usage: make_tb.py <system.v> <tb_sms.sv>
"""

import re
import sys

INPUTS = {
    "clk_sys": "clk", "ce_cpu": "ce_cpu", "ce_vdp": "ce_vdp", "ce_pix": "ce_pix", "ce_sp": "ce_sp",
    "gg": "cfg_gg", "ggres": "cfg_gg", "RESET_n": "reset_n", "rom_do": "rom_do",
    # Controller pins are active low.
    "j1_up": "~joy[3]", "j1_down": "~joy[2]", "j1_left": "~joy[1]", "j1_right": "~joy[0]",
    "j1_tl": "~joy[4]", "j1_tr": "~joy[5]", "j1_th": "1'b1", "j1_start": "~joy[6]", "j1_coin": "1'b1",
    "j1_a3": "~joy[6]",
    "j2_up": "1'b1", "j2_down": "1'b1", "j2_left": "1'b1", "j2_right": "1'b1", "j2_tl": "1'b1",
    "j2_tr": "1'b1", "j2_th": "1'b1", "j2_start": "1'b1", "j2_coin": "1'b1", "j2_a3": "1'b1",
    "pause": "~joy[6]", "x": "vx", "y": "vy", "vcounter_cpu": "vcounter_cpu", "palettemode": "cfg_sg",
    "pal": "cfg_pal", "region": "1'b0", "fm_ena": "1'b0", "dbr": "dbr", "ram_q": "ram_q",
    "nvram_q": "nvram_q", "ROMCL": "clk", "ROMAD": "dl_addr", "ROMDT": "dl_data", "ROMEN": "dl_en",
    "E0": "8'hFF", "F2": "8'hFF", "F3": "8'hFF", "sk1100_row_data": "12'hFFF",
}
OUTPUTS = {
    "rom_rd": "rom_rd", "rom_a": "rom_a", "color": "color", "mask_column": "mask_column",
    "smode_M1": "smode_M1", "smode_M2": "smode_M2", "smode_M3": "smode_M3", "smode_M4": "smode_M4",
    "audioL": "audio_l", "audioR": "audio_r", "ram_a": "ram_a", "ram_d": "ram_d", "ram_we": "ram_we",
    "nvram_a": "nvram_a", "nvram_d": "nvram_d", "nvram_we": "nvram_we",
}

TEMPLATE = """// Generated by fpga/sim/sms/make_tb.py: testbench around the SMS_MiSTer system and video entities.
module tb_sms(
  input  wire        clk,
  input  wire [6:0]  joy,       // 0 right, 1 left, 2 down, 3 up, 4 button 1, 5 button 2, 6 start/pause (1 = pressed)
  input  wire        cfg_gg,
  input  wire        cfg_pal,
  input  wire        cfg_sg,
  output wire [11:0] color,
  output wire [8:0]  vx,
  output wire [8:0]  vy,
  output wire        hblank,
  output wire        vblank,
  output reg         ce_pix,
  output wire [15:0] audio_l,
  output reg         ready
);
  // ROM image (+rom=<hex file> +romsize=<bytes>), replayed like the MiSTer download stream.
  integer romsize;
  reg [7:0] rom [0:4*1024*1024-1];
  initial begin
    string path;
    if (!$value$plusargs("rom=%s", path)) $fatal(1, "+rom= missing");
    if (!$value$plusargs("romsize=%d", romsize)) $fatal(1, "+romsize= missing");
    $readmemh(path, rom);
  end

  reg        dl_en = 0;
  reg [24:0] dl_addr = 0;
  reg [7:0]  dl_data = 0;
  reg [23:0] cart_mask = 0, cart_mask512 = 0;
  reg        cart_sz512 = 0;
  reg        dbr = 0;
  reg [3:0]  dl_phase = 0;
  reg [24:0] dl_next = 0;
  reg [15:0] post = 0;
  reg        reset_n = 0;
  initial ready = 0;
  always @(posedge clk) begin
    dl_en <= 0;
    if (!dbr) begin
      dl_phase <= dl_phase + 1;
      if (dl_phase == 0) begin
        if (dl_next < romsize) begin
          dl_en <= 1; dl_addr <= dl_next; dl_data <= rom[dl_next];
          cart_mask <= (dl_next == 0) ? 0 : (cart_mask | dl_next[23:0]);
          cart_mask512 <= (dl_next == 512) ? 0 : (cart_mask512 | (dl_next[23:0] - 24'd512));
          dl_next <= dl_next + 1;
        end else begin
          cart_sz512 <= (dl_addr[9:0] == 10'h1FF);
          dbr <= 1;
        end
      end
    end else if (!reset_n) begin
      post <= post + 1;
      if (post == 16'hFFFF) begin reset_n <= 1; ready <= 1; end
    end
  end

  // ROM reads (registered), with the mask of SMS.sv.
  wire        rom_rd;
  wire [23:0] rom_a;
  reg  [7:0]  rom_do;
  always @(posedge clk)
    rom_do <= rom[cart_sz512 ? ((rom_a + 24'd512) & cart_mask512) : (rom_a & cart_mask)];

  // Work RAM 16 KiB and cartridge RAM 32 KiB (starts at 0xFF), registered reads.
  wire [13:0] ram_a;  wire [7:0] ram_d;  wire ram_we;  reg [7:0] ram_q;
  reg  [7:0]  ram [0:16383];
  always @(posedge clk) begin if (ram_we) ram[ram_a] <= ram_d; ram_q <= ram_we ? ram_d : ram[ram_a]; end
  wire [14:0] nvram_a; wire [7:0] nvram_d; wire nvram_we; reg [7:0] nvram_q;
  reg  [7:0]  nvram [0:32767];
  integer k; initial for (k = 0; k < 32768; k = k + 1) nvram[k] = 8'hFF;
  always @(posedge clk) begin if (nvram_we) nvram[nvram_a] <= nvram_d; nvram_q <= nvram_we ? nvram_d : nvram[nvram_a]; end

  // Clock enables, as SMS.sv (negedge).
  reg ce_cpu = 0, ce_vdp = 0, ce_sp = 0;
  reg [4:0] clkd = 0;
  initial ce_pix = 0;
  always @(negedge clk) begin
    ce_sp <= clkd[0]; ce_vdp <= 0; ce_pix <= 0; ce_cpu <= 0;
    clkd <= clkd + 1'd1;
    if (clkd == 29) begin clkd <= 0; ce_vdp <= 1; ce_pix <= 1; end
    else if (clkd == 24) begin ce_cpu <= 1; ce_vdp <= 1; end
    else if (clkd == 19) begin ce_vdp <= 1; ce_pix <= 1; end
    else if (clkd == 14) begin ce_vdp <= 1; end
    else if (clkd == 9) begin ce_cpu <= 1; ce_vdp <= 1; ce_pix <= 1; end
    else if (clkd == 4) begin ce_vdp <= 1; end
  end

  wire mask_column, smode_M1, smode_M2, smode_M3, smode_M4;
  wire [7:0] vcounter_cpu;
  wire [15:0] audio_r;

  video video (
    .clk(clk), .ce_pix(ce_pix), .pal(cfg_pal), .border(1'b0), .ggres(cfg_gg), .mask_column(mask_column),
    .cut_mask(1'b0), .smode_M1(smode_M1), .smode_M2(smode_M2), .smode_M3(smode_M3), .smode_M4(smode_M4),
    .video_state_out(), .video_state_in(22'd0), .video_state_set(1'b0),
    .x(vx), .y(vy), .vcounter_cpu(vcounter_cpu), .hsync(), .vsync(), .hblank(hblank), .vblank(vblank));

  system system (
@CONNECTIONS@
  );
endmodule
"""


def main() -> None:
    text = open(sys.argv[1]).read()
    start = text.index("\nmodule system\n")
    header = text[start:text.index(");", start)]
    ports = re.findall(r"(input|output)\s+(\[[^\]]+\])?\s*(\w+)", header)
    lines = []
    for direction, _width, name in ports:
        if direction == "input":
            lines.append(f"    .{name}({INPUTS.get(name, '0')})")
        else:
            lines.append(f"    .{name}({OUTPUTS.get(name, '')})")
    open(sys.argv[2], "w").write(TEMPLATE.replace("@CONNECTIONS@", ",\n".join(lines)))
    print(f"{sys.argv[2]}: {len(ports)} ports of system")


if __name__ == "__main__":
    main()
